student_id = input("請輸入完整學號：").strip().upper()
tail = student_id[-3:]
a = int(student_id[-3])
b = int(student_id[-2])
c = int(student_id[-1])
s = a + b + c

"""第一題"""

ads = [
    ("搜尋廣告", 1000 + 100 * a, 30 + 5 * b),
    ("社群廣告", 1200 + 100 * b, 24 + 4 * c),
    ("影音廣告", 0, 0),
]
target = 2.5 + 0.1 * c

def ad_report(impressions, clicks, target=3.0):
    if impressions == 0:
        return (None, False)
    ctr = (clicks / impressions) * 100
    passed = ctr >= target
    return (ctr, passed)

# 輸出基本資訊：學號、計算出的個人門檻 (即變數 target)
print(f"學號: {student_id}")
print(f"個人達標門檻 (target): {target}%")
print("-" * 60)

passed_count = 0
print(f"{'廣告名稱':<10}{'曝光次數':<10}{'點擊次數':<10}{'CTR (%)':<12}{'是否達標':<10}")

# 依據前一個單元格定義的 ads 列表進行逐筆計算
for name, impressions, clicks in ads:
    # 以關鍵字引數將 target 傳入
    ctr, passed = ad_report(impressions, clicks, target=target)

    # 顯示格式處理
    if ctr is None:
        ctr_str = "None"
    else:
        ctr_str = f"{ctr:.2f}%"

    print(f"{name:<12}{impressions:<12}{clicks:<12}{ctr_str:<15}{str(passed):<10}")

    if passed:
        passed_count += 1

print("-" * 60)
print(f"總達標廣告數: {passed_count}")
print("-" * 60)

# 驗證預設門檻與零點擊
print("驗證預設門檻 (ad_report(1000, 30)):", ad_report(1000, 30))
print("驗證零點擊廣告 (ad_report(1000, 0)):", ad_report(1000, 0))