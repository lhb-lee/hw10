student_id = input("請輸入完整學號：").strip().upper()
tail = student_id[-3:]
a = int(student_id[-3])
b = int(student_id[-2])
c = int(student_id[-1])
s = a + b + c

saved = ["BASE"]
raw_a = [" welcome" + tail + " ", "vip" + tail, "",
         "WELCOME" + tail, "   "]
raw_b = [" new" + tail + " ", " welcome" + tail + " "]

def collect_codes(raw_codes, saved=None):
    # 建立一個新的串列以避免修改原本的 saved
    result = list(saved) if saved is not None else []
    # 使用 set 來快速查詢已存在的值（保證大寫與唯一性）
    seen = set(result)

    for raw in raw_codes:
        cleaned = raw.strip().upper()
        if cleaned == "":
            continue
        if cleaned not in seen:
            seen.add(cleaned)
            result.append(cleaned)

    return result

# 複製一份原始的 saved 與 raw_a 以確保後續印出的是「原始狀態」
original_saved = list(saved)
original_raw_a = list(raw_a)

# 依序計算 activity_a 與 activity_b
activity_a = collect_codes(raw_a, saved=saved)
activity_b = collect_codes(raw_b)

# 印出學號、活動 A 結果、活動 B 結果、原始 saved 與原始 raw_a
print("學號:", student_id)
print("活動 A 結果 :", activity_a)
print("活動 B 結果 :", activity_b)
print("原始 Saved :", original_saved)
print("原始 raw_a :", original_raw_a)

# 測試空資料
empty_test = collect_codes([])
print("測試空資料結果 ):", empty_test)