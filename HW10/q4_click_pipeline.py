student_id = input("請輸入完整學號：").strip().upper()
tail = student_id[-3:]
a = int(student_id[-3])
b = int(student_id[-2])
c = int(student_id[-1])
s = a + b + c

raw_clicks = [str(10 + a), "0", "", " " + str(5 + b) + " ",
              "   ", str(15 + c), str(5 + b)]
min_clicks = 5 + b

def select_clicks(raw_clicks, min_clicks=10):
    # 1. map() 搭配 lambda，去掉每筆文字的頭尾空白
    stripped = map(lambda x: x.strip(), raw_clicks)

    # 2. filter(None, ...)，刪掉空字串
    non_empty = filter(None, stripped)

    # 3. map(int, ...) 轉整數，並用 list() 保存結果
    numbers = list(map(int, non_empty))

    # 4. qualified 是 numbers 中大於或等於 min_clicks 的項目。使用 filter() 搭配 lambda，再用 list() 保存
    qualified = list(filter(lambda x: x >= min_clicks, numbers))

    return (numbers, qualified)

# 測試與輸出
print(f"學號: {student_id}")
print(f"點擊門檻: {min_clicks}")

# 呼叫函式
numbers, qualified = select_clicks(raw_clicks, min_clicks=min_clicks)
print(f"清理後的項目結果: {numbers}")
print(f"合格項目: {qualified}")
print(f"合格筆數: {len(qualified)} 筆")
print(f"合格點擊合計: {sum(qualified)} 次\n")

# 在函式外使用 sorted 由大到小排序，再用 enumerate 印出排名
print("--- 合格項目排名 (門檻: {0}) ---".format(min_clicks))
sorted_qualified = sorted(qualified, reverse=True)
for rank, clicks in enumerate(sorted_qualified, start=1):
    print(f"第{rank}名: {clicks} 次")

