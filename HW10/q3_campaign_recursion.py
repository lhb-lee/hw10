student_id = input("請輸入完整學號：").strip().upper()
tail = student_id[-3:]
a = int(student_id[-3])
b = int(student_id[-2])
c = int(student_id[-1])
s = a + b + c

daily_spend = [100 + 10 * a, 150 + 10 * b, 0,
               200 + 10 * c, 50 + 10 * s]
n = 3 + c % 3

def cumulative_spend(daily_spend, n):
    # 遞迴停止條件
    if n == 0:
        return 0
    # 遞迴縮小問題並加上第 n 天的費用（索引為 n-1）
    return cumulative_spend(daily_spend, n - 1) + daily_spend[n - 1]

# 印出基本學號與每日費用資訊
print(f"學號: {student_id}")
print(f"每日費用: {daily_spend}")
print(f"指定天數 n: {n}")

# 1. 印出指定前 n 天的累計費用
ans = cumulative_spend(daily_spend, n)
print(f"前 {n} 天累計費用: {ans} 元")

print("\n--- =前 0 到 5 天的累計費用 ---")
# 2. 依序印出前 0、1、2、3、4、5 天的累計費用
for i in range(6):
    print(f"前 {i} 天累計費用: {cumulative_spend(daily_spend, i)} 元")

# 3. 呼叫 cumulative_spend([], 0) 印出空資料結果
print(f"空資料: {cumulative_spend([], 0)} 元")